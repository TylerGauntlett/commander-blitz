"""Pin the Python dependencies CI and the image install (TECH_DEBT DEP-01).

    python scripts/lock_deps.py           # rewrite constraints.txt
    python scripts/lock_deps.py --check   # exit 1 if it is out of date with pyproject

``pyproject.toml`` keeps its ``>=`` ranges -- they say what the code supports.
``constraints.txt`` says what CI actually tested, so a release that lands
overnight cannot turn a green branch red without a commit. It is resolved for
the platform CI and the Dockerfile run on (CPython 3.13, manylinux x86-64), not
for the machine running this script, using pip's own resolver in dry-run mode.

Environment markers are still evaluated against the host, so a Windows run may
pin a Windows-only package (``colorama``). That is harmless: a constraint caps a
version, it never causes an install.

``train`` (torch) is left out on purpose: nothing in CI installs it.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "constraints.txt"
PLATFORMS = ("manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64")
HEADER = (
    "# Generated by scripts/lock_deps.py -- do not edit by hand.\n"
    "# What CI and the Dockerfile install, resolved for CPython 3.13 on manylinux.\n"
    "# Refresh: python scripts/lock_deps.py\n"
)


def requirements() -> list[str]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    return [*project["dependencies"], *project["optional-dependencies"]["dev"]]


def resolve(reqs: list[str]) -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        command = [
            sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
            "--quiet", "--report", str(report), "--target", str(Path(tmp) / "t"),
            "--python-version", "3.13", "--implementation", "cp", "--only-binary=:all:",
        ]
        for platform in PLATFORMS:
            command += ["--platform", platform]
        subprocess.run([*command, *reqs], check=True)
        installs = json.loads(report.read_text(encoding="utf-8"))["install"]
    pins = {i["metadata"]["name"].lower(): i["metadata"]["version"] for i in installs}
    return [f"{name}=={version}" for name, version in sorted(pins.items())]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if a requirement in pyproject has no pin (does not re-resolve)",
    )
    args = parser.parse_args()

    if args.check:
        pinned = {
            line.split("==")[0]
            for line in OUT.read_text(encoding="utf-8").splitlines()
            if "==" in line
        }
        missing = []
        for req in requirements():
            name = req.split(";")[0].split("[")[0]
            for sep in (">", "<", "=", "!", "~", " "):
                name = name.split(sep)[0]
            if name.lower().replace("_", "-") not in {p.replace("_", "-") for p in pinned}:
                missing.append(name)
        if missing:
            print(f"constraints.txt has no pin for: {', '.join(missing)}")
            print("run: python scripts/lock_deps.py")
            return 1
        print("constraints.txt pins every requirement")
        return 0

    pins = resolve(requirements())
    OUT.write_text(HEADER + "\n".join(pins) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(pins)} pins to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

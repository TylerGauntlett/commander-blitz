"""The feature backlog as data: one item per file, a derived queue, a generated page.

    python scripts/roadmap.py --check            exit 1 if an item is malformed or the page is stale
    python scripts/roadmap.py --write            regenerate docs/roadmap.md wholesale
    python scripts/roadmap.py --next             the ready items, best first; --json for a machine
    python scripts/roadmap.py --show <id>        print one item
    python scripts/roadmap.py --new <id> --title ... --area ... --effort ... --impact ... --why ...
    python scripts/roadmap.py --start <id>       mark an item in progress
    python scripts/roadmap.py --done <id>        retire an item and unblock what depended on it
    python scripts/roadmap.py --drop <id>        retire an item without delivering it

``docs/roadmap.md`` began as prose. Prose can be read but not queried: nothing
could ask "what is the most valuable thing I can start today?" without a person
re-reading the page, and nothing noticed when an item's blockers were long since
delivered. So the items moved to ``docs/roadmap/<id>.md``, each with a small
front matter the ``/plan-feature`` skill writes and the ``/extend-roadmap``
skill reads, and the page is **regenerated wholesale** from them, never edited.

The front matter is a flat subset of YAML, parsed here so the script stays
stdlib only (``validate_decks.py`` and ``build_card_index.py`` keep the same
rule): ``key: value``, lists as ``[a, b]``, booleans as ``true``/``false``.

What is held, and where it is held, is the same shape as
``gen_dsl_reference.py``: ``--check`` fails on a malformed item, a dependency
on an id that does not exist, a cycle, a missing section, a placeholder left
behind by ``--new``, a dead link, or a committed page that differs from what
this script would write now. ``scripts/verify.py`` runs ``--check`` in its lint
group and ``tests/unit/roadmap/`` holds the rules on synthetic items.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
ITEMS_DIR = DOCS / "roadmap"
PAGE = DOCS / "roadmap.md"

HEADER = (
    "<!-- Generated by scripts/roadmap.py from docs/roadmap/*.md. Do not edit by hand; "
    "regenerate with `python scripts/roadmap.py --write`. -->\n"
)

#: The areas an item may belong to, in the order the page lists them.
AREAS: dict[str, str] = {
    "site": "Operating the site",
    "brand": "Presentation and branding",
    "cards": "Cards",
    "decks": "Decks",
    "play": "Play experience",
    "steamdeck": "The Steam Deck build",
    "cpus": "Advanced CPUs",
    "matchmaking": "Matchmaking",
}

#: Rank order. Lower sorts first.
IMPACTS: dict[str, int] = {"high": 0, "medium": 1, "low": 2}
EFFORTS: dict[str, int] = {"S": 0, "M": 1, "L": 2}
STATUSES = ("proposed", "in_progress")

#: The sections every item carries, in this order. `--new` scaffolds them and
#: `--check` refuses an item without them.
SECTIONS = ("Today", "The change", "Gate")

#: What `--new` writes into an empty section; `--check` refuses it, so a
#: scaffold cannot be committed as a plan.
PLACEHOLDER = "<!-- fill me in -->"

REQUIRED_KEYS = ("id", "title", "area", "effort", "impact", "why")
OPTIONAL_KEYS = ("depends_on", "status", "continuous", "adr")
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
LINK_RE = re.compile(r"\]\(([^)\s]+)\)")


class RoadmapError(Exception):
    """A malformed item or an inconsistent backlog; `--check` prints these."""


@dataclass
class Item:
    id: str
    title: str
    area: str
    effort: str
    impact: str
    why: str
    body: str
    depends_on: list[str] = field(default_factory=list)
    status: str = "proposed"
    continuous: bool = False
    adr: bool = False
    path: Path | None = None

    @property
    def effort_label(self) -> str:
        return f"{self.effort}, continuous" if self.continuous else self.effort

    @property
    def slug(self) -> str:
        return slugify(self.title)


# --------------------------------------------------------------------------
# Front matter


def parse_front_matter(text: str) -> tuple[dict[str, object], str]:
    """Split a file into its flat front matter and its body."""
    if not text.startswith("---\n"):
        raise RoadmapError("no front matter: the file must open with `---`")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise RoadmapError("unterminated front matter: no closing `---`")
    meta: dict[str, object] = {}
    for raw in text[4:end].splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise RoadmapError(f"front matter line is not `key: value`: {raw!r}")
        key, value = line.split(":", 1)
        key = key.strip()
        if key in meta:
            raise RoadmapError(f"duplicate front matter key {key!r}")
        meta[key] = _parse_value(value.strip())
    return meta, text[end + 5 :]


def _parse_value(value: str) -> object:
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        return [v.strip().strip("'\"") for v in inner.split(",") if v.strip()] if inner else []
    if value in ("true", "false"):
        return value == "true"
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value


def render_front_matter(item: Item) -> str:
    lines = [
        "---",
        f"id: {item.id}",
        f"title: {_quote(item.title)}",
        f"area: {item.area}",
        f"effort: {item.effort}",
        f"impact: {item.impact}",
        f"why: {_quote(item.why)}",
        f"depends_on: [{', '.join(item.depends_on)}]",
        f"status: {item.status}",
    ]
    if item.continuous:
        lines.append("continuous: true")
    if item.adr:
        lines.append("adr: true")
    lines.append("---")
    return "\n".join(lines) + "\n"


def _quote(value: str) -> str:
    return '"' + value.replace('"', "'") + '"' if ":" in value or value.startswith("[") else value


# --------------------------------------------------------------------------
# Items


def parse_item(text: str, path: Path | None = None) -> Item:
    meta, body = parse_front_matter(text)
    missing = [k for k in REQUIRED_KEYS if k not in meta]
    if missing:
        raise RoadmapError(f"missing front matter keys: {missing}")
    unknown = sorted(set(meta) - set(REQUIRED_KEYS) - set(OPTIONAL_KEYS))
    if unknown:
        raise RoadmapError(f"unknown front matter keys: {unknown}")
    item = Item(
        id=str(meta["id"]),
        title=str(meta["title"]),
        area=str(meta["area"]),
        effort=str(meta["effort"]),
        impact=str(meta["impact"]),
        why=str(meta["why"]),
        body=body.strip("\n") + "\n",
        depends_on=list(meta.get("depends_on", [])),  # type: ignore[arg-type]
        status=str(meta.get("status", "proposed")),
        continuous=bool(meta.get("continuous", False)),
        adr=bool(meta.get("adr", False)),
        path=path,
    )
    validate_item(item)
    return item


def validate_item(item: Item) -> None:
    if not ID_RE.match(item.id):
        raise RoadmapError(f"id {item.id!r} is not kebab-case")
    if item.path is not None and item.path.stem != item.id:
        raise RoadmapError(f"id {item.id!r} does not match file name {item.path.name!r}")
    if item.area not in AREAS:
        raise RoadmapError(f"area {item.area!r} is not one of {list(AREAS)}")
    if item.effort not in EFFORTS:
        raise RoadmapError(f"effort {item.effort!r} is not one of {list(EFFORTS)}")
    if item.impact not in IMPACTS:
        raise RoadmapError(f"impact {item.impact!r} is not one of {list(IMPACTS)}")
    if item.status not in STATUSES:
        raise RoadmapError(f"status {item.status!r} is not one of {STATUSES}")
    if not item.title.strip() or not item.why.strip():
        raise RoadmapError("title and why must not be empty")
    if not isinstance(item.depends_on, list):
        raise RoadmapError("depends_on must be a list")
    if item.id in item.depends_on:
        raise RoadmapError(f"{item.id} depends on itself")
    if len(set(item.depends_on)) != len(item.depends_on):
        raise RoadmapError(f"{item.id} lists a dependency twice")
    if PLACEHOLDER in item.body:
        raise RoadmapError(f"{item.id} still has a {PLACEHOLDER!r} left by --new")
    if re.search(r"^# ", item.body, re.M):
        raise RoadmapError(f"{item.id} has a top-level heading; sections are `## `")
    found = [m.group(1) for m in re.finditer(r"^## (.+)$", item.body, re.M)]
    if found[: len(SECTIONS)] != list(SECTIONS):
        raise RoadmapError(
            f"{item.id} must open with the sections {list(SECTIONS)} in order; found {found}"
        )
    for name in SECTIONS:
        if not _section_text(item.body, name).strip():
            raise RoadmapError(f"{item.id}: section {name!r} is empty")


def _section_text(body: str, name: str) -> str:
    match = re.search(rf"^## {re.escape(name)}\n(.*?)(?=^## |\Z)", body, re.M | re.S)
    return match.group(1) if match else ""


def _rel(path: Path) -> str:
    """A path for a message: repository-relative when it is in the repository."""
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return path.name


def load_items(items_dir: Path = ITEMS_DIR) -> list[Item]:
    items: list[Item] = []
    errors: list[str] = []
    for path in sorted(items_dir.glob("*.md")):
        if path.name.startswith("_"):
            continue
        try:
            items.append(parse_item(path.read_text(encoding="utf-8"), path))
        except RoadmapError as exc:
            errors.append(f"{_rel(path)}: {exc}")
    if errors:
        raise RoadmapError("\n".join(errors))
    validate_graph(items)
    return items


def validate_graph(items: list[Item]) -> None:
    by_id = {item.id: item for item in items}
    if len(by_id) != len(items):
        dupes = sorted({i.id for i in items if sum(j.id == i.id for j in items) > 1})
        raise RoadmapError(f"duplicate ids: {dupes}")
    for item in items:
        for dep in item.depends_on:
            if dep not in by_id:
                raise RoadmapError(f"{item.id} depends on {dep!r}, which is not an item")
    # A cycle means nothing in it can ever be ready.
    state: dict[str, int] = {}

    def visit(node: str, trail: list[str]) -> None:
        if state.get(node) == 1:
            cycle = [*trail[trail.index(node) :], node]
            raise RoadmapError("dependency cycle: " + " -> ".join(cycle))
        if state.get(node) == 2:
            return
        state[node] = 1
        for dep in by_id[node].depends_on:
            visit(dep, [*trail, node])
        state[node] = 2

    for item in items:
        visit(item.id, [])


# --------------------------------------------------------------------------
# The queue


def unlocks(items: list[Item]) -> dict[str, int]:
    """How many items, transitively, wait on each one."""
    by_id = {item.id: item for item in items}
    dependants: dict[str, set[str]] = {item.id: set() for item in items}
    for item in items:
        for dep in item.depends_on:
            dependants[dep].add(item.id)

    def closure(node: str) -> set[str]:
        seen: set[str] = set()
        stack = list(dependants[node])
        while stack:
            cur = stack.pop()
            if cur in seen:
                continue
            seen.add(cur)
            stack.extend(dependants[cur])
        return seen

    return {node: len(closure(node)) for node in by_id}


def rank_key(item: Item, unlock: dict[str, int]) -> tuple:
    """Impact first, then effort, then what finishing it frees up."""
    return (IMPACTS[item.impact], EFFORTS[item.effort], -unlock[item.id], item.title.lower())


def ready(items: list[Item]) -> list[Item]:
    """Items that can start today: proposed, with no dependency still on the page."""
    unlock = unlocks(items)
    return sorted(
        (i for i in items if i.status == "proposed" and not i.depends_on),
        key=lambda i: rank_key(i, unlock),
    )


def blocked(items: list[Item]) -> list[Item]:
    unlock = unlocks(items)
    return sorted(
        (i for i in items if i.status == "proposed" and i.depends_on),
        key=lambda i: rank_key(i, unlock),
    )


def in_progress(items: list[Item]) -> list[Item]:
    return sorted((i for i in items if i.status == "in_progress"), key=lambda i: i.title.lower())


# --------------------------------------------------------------------------
# The page


def slugify(text: str) -> str:
    """GitHub's heading anchor rule, as `gen_dsl_reference.py` pins it."""
    text = re.sub(r"[`*]", "", text)
    text = text.lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def headings_in(path: Path) -> set[str]:
    return {
        slugify(m.group(1))
        for m in re.finditer(r"^#{1,6} (.+)$", path.read_text(encoding="utf-8"), re.M)
    }


def _fragment(name: str, items_dir: Path) -> str:
    path = items_dir / name
    return path.read_text(encoding="utf-8").strip("\n") + "\n" if path.exists() else ""


def _relink(body: str) -> str:
    """Item files live one directory down from the page; lift their links."""
    return body.replace("](../", "](")


def _demote(body: str) -> str:
    return re.sub(r"^(#{2,4}) ", lambda m: "#" * (len(m.group(1)) + 2) + " ", body, flags=re.M)


def property_line(item: Item, by_id: dict[str, Item]) -> str:
    deps = (
        ", ".join(f"[{by_id[d].title}](#{by_id[d].slug})" for d in item.depends_on)
        if item.depends_on
        else "nothing"
    )
    parts = [
        f"Effort **{item.effort_label}**",
        f"Impact **{item.impact}**, {item.why}",
        f"Depends on {deps}",
    ]
    if item.status == "in_progress":
        parts.append("**In progress**")
    if item.adr:
        parts.append("ADR first")
    return " · ".join(parts) + ".\n"


def generate(items_dir: Path = ITEMS_DIR) -> str:
    items = load_items(items_dir)
    by_id = {item.id: item for item in items}
    unlock = unlocks(items)
    out: list[str] = [HEADER, "\n# Roadmap\n\n", _relink(_fragment("_intro.md", items_dir))]

    # The grid: every item on one screen, best first.
    out.append("\n## The grid\n\n")
    out.append(
        "Every item, sorted by impact, then effort, then how many items finishing it\n"
        "frees up. The properties are the ones under each heading; this table is\n"
        "generated from them.\n\n"
    )
    out.append("| Item | Effort | Impact | Depends on | Unlocks |\n|---|---|---|---|---:|\n")
    for item in sorted(items, key=lambda i: rank_key(i, unlock)):
        deps = ", ".join(by_id[d].title for d in item.depends_on) or "nothing"
        out.append(
            f"| [{item.title}](#{item.slug}) | {item.effort_label} | {item.impact} | {deps} | {unlock[item.id]} |\n"
        )

    # The queue.
    out.append("\n## What to do next\n\n")
    out.append(
        "Derived from the properties: an item is **ready** when nothing it depends\n"
        "on is still on this page, and the ready items are ranked by impact, then\n"
        "effort, then what they unlock. `python scripts/roadmap.py --next` prints the\n"
        "same list, and `/extend-roadmap` starts at the top of it.\n\n"
    )
    going = in_progress(items)
    if going:
        out.append(
            "**In progress:** " + ", ".join(f"[{i.title}](#{i.slug})" for i in going) + ".\n\n"
        )
    out.append("**Ready now, best first:**\n\n")
    for n, item in enumerate(ready(items), 1):
        out.append(f"{n}. [{item.title}](#{item.slug}) — {item.effort_label}, {item.impact}\n")
    waiting = blocked(items)
    if waiting:
        out.append("\n**Blocked, and by what:**\n\n")
        for item in waiting:
            deps = ", ".join(f"[{by_id[d].title}](#{by_id[d].slug})" for d in item.depends_on)
            out.append(f"- [{item.title}](#{item.slug}) — {deps}\n")

    # The items, by area.
    for area, heading in AREAS.items():
        area_items = sorted((i for i in items if i.area == area), key=lambda i: rank_key(i, unlock))
        if not area_items:
            continue
        out.append(f"\n## {heading}\n")
        for item in area_items:
            out.append(f"\n### {item.title}\n\n")
            out.append(property_line(item, by_id))
            out.append("\n" + _relink(_demote(item.body)))

    tail = _fragment("_not-planned.md", items_dir)
    if tail:
        out.append("\n" + _relink(tail))
    return "".join(out)


# --------------------------------------------------------------------------
# Checks


def link_problems(items: list[Item], items_dir: Path = ITEMS_DIR) -> list[str]:
    """Every relative link in an item lands on a file, and on a heading in it."""
    problems: list[str] = []
    page_slugs = {i.slug for i in items} | {"the-grid", "what-to-do-next"}
    sources = [(item.id, item.body) for item in items]
    # The prose fragments link the same way and are checked the same way.
    sources += [
        (path.name, path.read_text(encoding="utf-8")) for path in sorted(items_dir.glob("_*.md"))
    ]
    for item_id, body in sources:
        for target in LINK_RE.findall(body):
            if "://" in target or target.startswith("mailto:"):
                continue
            file, _, anchor = target.partition("#")
            if not file:
                if anchor not in page_slugs:
                    problems.append(f"{item_id}: #{anchor} is not an item or a page section")
                continue
            path = (items_dir / file).resolve()
            if not path.exists():
                problems.append(f"{item_id}: {target} does not exist")
                continue
            if anchor and path.suffix == ".md" and anchor not in headings_in(path):
                problems.append(f"{item_id}: {target} has no such heading")
    return problems


def check(items_dir: Path = ITEMS_DIR, page: Path = PAGE) -> list[str]:
    try:
        items = load_items(items_dir)
    except RoadmapError as exc:
        return str(exc).splitlines()
    problems = link_problems(items, items_dir)
    text = generate(items_dir)
    if not page.exists():
        problems.append(f"{page.relative_to(ROOT)} is missing; run --write")
    elif page.read_text(encoding="utf-8") != text:
        problems.append(
            f"{page.relative_to(ROOT)} is stale; run `python scripts/roadmap.py --write`"
        )
    return problems


# --------------------------------------------------------------------------
# Mutations


def scaffold(
    id_: str,
    title: str,
    area: str,
    effort: str,
    impact: str,
    why: str,
    depends_on: list[str],
    continuous: bool,
    adr: bool,
) -> str:
    item = Item(
        id=id_,
        title=title,
        area=area,
        effort=effort,
        impact=impact,
        why=why,
        body="",
        depends_on=depends_on,
        continuous=continuous,
        adr=adr,
    )
    body = "".join(f"\n## {name}\n\n{PLACEHOLDER}\n" for name in SECTIONS)
    return render_front_matter(item) + body


def write_item(item: Item, items_dir: Path = ITEMS_DIR) -> Path:
    path = items_dir / f"{item.id}.md"
    path.write_text(render_front_matter(item) + "\n" + item.body, encoding="utf-8", newline="\n")
    return path


def retire(id_: str, items_dir: Path = ITEMS_DIR) -> list[str]:
    """Delete an item and drop it from every `depends_on`; returns what was unblocked."""
    items = load_items(items_dir)
    by_id = {item.id: item for item in items}
    if id_ not in by_id:
        raise RoadmapError(f"no item {id_!r}")
    freed: list[str] = []
    for item in items:
        if id_ in item.depends_on:
            item.depends_on.remove(id_)
            write_item(item, items_dir)
            if not item.depends_on:
                freed.append(item.id)
    (items_dir / f"{id_}.md").unlink()
    return freed


# --------------------------------------------------------------------------
# CLI


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--next", action="store_true")
    ap.add_argument("--json", action="store_true", help="with --next: machine-readable")
    ap.add_argument("--show", metavar="ID")
    ap.add_argument("--new", metavar="ID")
    ap.add_argument("--title")
    ap.add_argument("--area", choices=list(AREAS))
    ap.add_argument("--effort", choices=list(EFFORTS))
    ap.add_argument("--impact", choices=list(IMPACTS))
    ap.add_argument("--why")
    ap.add_argument("--depends", default="", help="comma-separated ids")
    ap.add_argument("--continuous", action="store_true")
    ap.add_argument("--adr", action="store_true")
    ap.add_argument("--start", metavar="ID")
    ap.add_argument("--done", metavar="ID")
    ap.add_argument("--drop", metavar="ID")
    args = ap.parse_args(argv)

    try:
        if args.new:
            missing = [
                k for k in ("title", "area", "effort", "impact", "why") if not getattr(args, k)
            ]
            if missing:
                ap.error(f"--new needs --{' --'.join(missing)}")
            if not ID_RE.match(args.new):
                ap.error(f"{args.new!r} is not kebab-case")
            path = ITEMS_DIR / f"{args.new}.md"
            if path.exists():
                ap.error(f"{path.relative_to(ROOT)} already exists")
            deps = [d.strip() for d in args.depends.split(",") if d.strip()]
            known = {i.id for i in load_items()}
            unknown = [d for d in deps if d not in known]
            if unknown:
                ap.error(f"unknown dependencies: {unknown}")
            path.write_text(
                scaffold(
                    args.new,
                    args.title,
                    args.area,
                    args.effort,
                    args.impact,
                    args.why,
                    deps,
                    args.continuous,
                    args.adr,
                ),
                encoding="utf-8",
                newline="\n",
            )
            print(f"wrote {path.relative_to(ROOT)}; fill its sections, then --write")
            return 0

        if args.show:
            path = ITEMS_DIR / f"{args.show}.md"
            if not path.exists():
                ap.error(f"no item {args.show!r}")
            print(path.read_text(encoding="utf-8"), end="")
            return 0

        if args.start:
            items = {i.id: i for i in load_items()}
            if args.start not in items:
                ap.error(f"no item {args.start!r}")
            item = items[args.start]
            if item.depends_on:
                ap.error(f"{item.id} is blocked by {item.depends_on}; deliver those first")
            item.status = "in_progress"
            write_item(item)
            print(f"{item.id} is in progress; run --write")
            return 0

        if args.done or args.drop:
            id_ = args.done or args.drop
            items = {i.id: i for i in load_items()}
            if id_ not in items:
                ap.error(f"no item {id_!r}")
            if args.done and items[id_].continuous:
                ap.error(
                    f"{id_} is continuous: it is never done, only advanced. Leave it on the page"
                )
            freed = retire(id_)
            print(f"retired {id_}" + (f"; now ready: {', '.join(freed)}" if freed else ""))
            print("run --write")
            return 0

        if args.next:
            items = load_items()
            unlock = unlocks(items)
            rows = [
                {
                    "id": i.id,
                    "title": i.title,
                    "effort": i.effort_label,
                    "impact": i.impact,
                    "unlocks": unlock[i.id],
                    "adr": i.adr,
                }
                for i in ready(items)
            ]
            if args.json:
                print(
                    json.dumps(
                        {
                            "ready": rows,
                            "in_progress": [i.id for i in in_progress(items)],
                            "blocked": {i.id: i.depends_on for i in blocked(items)},
                        },
                        indent=2,
                    )
                )
            else:
                going = in_progress(items)
                if going:
                    print("in progress: " + ", ".join(i.id for i in going))
                print("ready, best first:")
                for row in rows:
                    flag = "  (ADR first)" if row["adr"] else ""
                    print(
                        f"  {row['id']:<28} {row['effort']:<14} {row['impact']:<7} unlocks {row['unlocks']}{flag}"
                    )
                for item in blocked(items):
                    print(f"  blocked: {item.id:<19} by {', '.join(item.depends_on)}")
            return 0

        if args.write:
            PAGE.write_text(generate(), encoding="utf-8", newline="\n")
            print(f"wrote {PAGE.relative_to(ROOT)}")
            return 0

        if args.check:
            problems = check()
            if problems:
                print("\n".join(problems))
                return 1
            print("roadmap ok")
            return 0
    except RoadmapError as exc:
        print(str(exc))
        return 1

    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
